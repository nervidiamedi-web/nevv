/**
 * Looks up direct images from the registry based on product slug, id, or name.
 */
export function getProductDirectImages(identifier?: string | null): { primary: string; gallery: string[] } | null {
  if (!identifier) return null;
  const key = String(identifier).toLowerCase().trim();

  // Exact match in registry
  if (PRODUCT_IMAGE_REGISTRY[key]) {
    return PRODUCT_IMAGE_REGISTRY[key];
  }

  // Substring or slug match
  for (const [regKey, val] of Object.entries(PRODUCT_IMAGE_REGISTRY)) {
    if (key.includes(regKey) || regKey.includes(key)) {
      return val;
    }
  }

  // Heuristic matching based on product characteristics
  if (key.includes('oily')) {
    return PRODUCT_IMAGE_REGISTRY['cetaphil-oily-skin-cleanser-125ml'];
  }
  if (key.includes('gentle') && (key.includes('clean') || key.includes('wash') || key.includes('125'))) {
    return PRODUCT_IMAGE_REGISTRY['cetaphil-gentle-skin-cleanser-125ml'];
  }
  if (key.includes('591') || (key.includes('daily') && key.includes('facial'))) {
    return PRODUCT_IMAGE_REGISTRY['cetaphil-daily-facial-cleanser-591ml'];
  }
  if (key.includes('85g') || (key.includes('cream') && (key.includes('85') || key.includes('normal')))) {
    return PRODUCT_IMAGE_REGISTRY['cetaphil-moisturizing-cream-85g'];
  }
  if (key.includes('453g') || (key.includes('cream') && (key.includes('453') || key.includes('very dry')))) {
    return PRODUCT_IMAGE_REGISTRY['cetaphil-moisturizing-cream-453g'];
  }
  if (key.includes('sun') || key.includes('spf') || key.includes('light gel')) {
    return PRODUCT_IMAGE_REGISTRY['cetaphil-sun-spf-50-light-gel-50ml'];
  }
  if (key.includes('dam') || key.includes('advance') || key.includes('body lotion')) {
    return PRODUCT_IMAGE_REGISTRY['cetaphil-dam-lotion-100g'];
  }
  if (key.includes('calendula')) {
    return PRODUCT_IMAGE_REGISTRY['cetaphil-baby-calendula-lotion-400ml'];
  }
  if (key.includes('shampoo')) {
    return PRODUCT_IMAGE_REGISTRY['cetaphil-baby-shampoo-200ml'];
  }
  if (key.includes('baby') && (key.includes('daily') || key.includes('lotion'))) {
    return PRODUCT_IMAGE_REGISTRY['cetaphil-baby-daily-lotion-400ml'];
  }

  return null;
}

/**
 * Converts an Imgur page URL (e.g. https://imgur.com/IxpPRLh or https://imgur.com/a/Gqr4XQJ)
 * into a direct image CDN URL (e.g. https://i.imgur.com/IxpPRLh.png).
 * If url is null, empty, or generic, looks up the right image for the product.
 */
export function toDirectImageUrl(url: string | undefined | null, productIdentifier?: string | null): string {
  // If no URL, or if URL is an accidental oily cleanser placeholder applied to a different product
  if (!url || typeof url !== 'string' || !url.trim()) {
    if (productIdentifier) {
      const matched = getProductDirectImages(productIdentifier);
      if (matched) return matched.primary;
    }
    return 'https://i.imgur.com/IxpPRLh.png';
  }

  const trimmed = url.trim();

  // If the product is NOT the oily cleanser, but got assigned the oily cleanser image by mistake
  if (productIdentifier && trimmed.includes('QexihB2')) {
    const idLower = productIdentifier.toLowerCase();
    if (!idLower.includes('oily')) {
      const correctImages = getProductDirectImages(productIdentifier);
      if (correctImages) {
        return correctImages.primary;
      }
    }
  }

  // Specific album and image mapping requested by user
  if (trimmed.includes('PRBLm6f')) {
    return 'https://i.imgur.com/OUSWZFX.png';
  }
  if (trimmed.includes('1hfncF3')) {
    return 'https://i.imgur.com/1hfncF3.png';
  }
  if (trimmed.includes('ubdzYUt') || trimmed.includes('u04vmdz')) {
    return 'https://i.imgur.com/u04vmdz.png';
  }

  // Already a direct i.imgur.com CDN link with extension
  if (trimmed.includes('i.imgur.com') && /\.(png|jpg|jpeg|webp|gif)$/i.test(trimmed)) {
    return trimmed;
  }

  // If i.imgur.com without extension
  const directMatch = trimmed.match(/i\.imgur\.com\/([a-zA-Z0-9]+)/);
  if (directMatch && directMatch[1]) {
    return `https://i.imgur.com/${directMatch[1]}.png`;
  }

  // Extract ID from https://imgur.com/a/ID or https://imgur.com/ID
  const pageMatch = trimmed.match(/imgur\.com\/(?:a\/)?([a-zA-Z0-9]+)/);
  if (pageMatch && pageMatch[1]) {
    return `https://i.imgur.com/${pageMatch[1]}.png`;
  }

  return trimmed;
}

/**
 * Normalizes an array of image URLs to direct image URLs.
 */
export function toDirectImageUrls(
  urls: (string | undefined | null)[] | undefined | null,
  productIdentifier?: string | null
): string[] {
  if (urls && Array.isArray(urls) && urls.length > 0) {
    const direct = urls
      .filter((u): u is string => Boolean(u && typeof u === 'string' && u.trim()))
      .map(u => toDirectImageUrl(u, productIdentifier));
    
    // Check if array has non-placeholder valid items
    if (direct.length > 0) {
      return direct;
    }
  }

  if (productIdentifier) {
    const matched = getProductDirectImages(productIdentifier);
    if (matched && matched.gallery.length > 0) {
      return matched.gallery;
    }
  }

  return ['https://i.imgur.com/IxpPRLh.png'];
}

/**
 * Calculates the average star rating from a list of reviews.
 */
export function calculateReviewRating(reviews: Array<{ rating?: number }> | undefined | null, fallback = 5): number {
  if (!reviews || !Array.isArray(reviews) || reviews.length === 0) {
    return fallback;
  }
  const sum = reviews.reduce((acc, curr) => acc + (Number(curr.rating) || 5), 0);
  const avg = sum / reviews.length;
  return Math.round(avg * 10) / 10;
}
